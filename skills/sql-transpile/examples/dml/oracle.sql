-- @id: I09
-- @note: あれば加算、無ければ挿入する upsert（列を参照する更新）
-- @check: SELECT qty FROM stock WHERE warehouse_id = 1 AND product_id = 102
-- @expect-scalardb: ERROR
MERGE INTO stock s
USING (SELECT 1 AS warehouse_id, 102 AS product_id, 10 AS qty FROM dual) src
ON (s.warehouse_id = src.warehouse_id AND s.product_id = src.product_id)
WHEN MATCHED THEN UPDATE SET s.qty = s.qty + src.qty
WHEN NOT MATCHED THEN INSERT (warehouse_id, product_id, qty) VALUES (src.warehouse_id, src.product_id, src.qty);
