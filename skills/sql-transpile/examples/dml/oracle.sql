CREATE TABLE customers (customer_id NUMBER(6) PRIMARY KEY, name VARCHAR2(40), email VARCHAR2(60), region VARCHAR2(10), vip NUMBER(1), created_at DATE);
CREATE TABLE products (product_id NUMBER(6) PRIMARY KEY, name VARCHAR2(40), category VARCHAR2(20), price NUMBER(9,2), active NUMBER(1));
CREATE TABLE orders (order_id NUMBER(8) PRIMARY KEY, customer_id NUMBER(6), order_date DATE, status VARCHAR2(10) DEFAULT 'NEW', total NUMBER(10,2), note VARCHAR2(100));
CREATE INDEX idx_orders_customer ON orders (customer_id);
CREATE TABLE order_items (order_id NUMBER(8), line_no NUMBER(3), product_id NUMBER(6), qty NUMBER(5), unit_price NUMBER(9,2), PRIMARY KEY (order_id, line_no));
CREATE TABLE stock (warehouse_id NUMBER(4), product_id NUMBER(6), qty NUMBER(7), updated_at TIMESTAMP, PRIMARY KEY (warehouse_id, product_id));
CREATE TABLE audit_log (log_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY, table_name VARCHAR2(30), action VARCHAR2(10), logged_at TIMESTAMP);
CREATE TABLE seq_counter (name VARCHAR2(30) PRIMARY KEY, next_val NUMBER(10));
CREATE SEQUENCE order_seq START WITH 5000;
