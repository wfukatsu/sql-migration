ON (p.product_id = src.product_id)
WHEN MATCHED THEN UPDATE SET p.name = src.name, p.price = src.price
WHEN NOT MATCHED THEN INSERT (product_id, name, category, price, active) VALUES (src.product_id, src.name, src.category, src.price, src.active);
