--==============================================================================
-- 4. 自律型トランザクション（呼び出し元のロールバックに影響されないログ出力）[ORA]
--==============================================================================
CREATE OR REPLACE PROCEDURE log_msg (p_msg VARCHAR2) AS
  PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
  INSERT INTO emp_audit (action, message) VALUES ('LOG', p_msg);
  COMMIT;                                       -- 自身のトランザクションのみ確定
END;
/

BEGIN
  UPDATE employees SET salary = salary + 1 WHERE employee_id = 100;
  log_msg('社長の給与を変更しようとした');
  ROLLBACK;                                     -- UPDATE は戻るがログは残る
END;
/
SELECT action, message FROM emp_audit;

