-- 5-1. BEFORE 行トリガー：値の補正と検証（:NEW / :OLD）
CREATE OR REPLACE TRIGGER emp_biu_trg
  BEFORE INSERT OR UPDATE OF salary, email ON employees
  FOR EACH ROW
BEGIN
  :NEW.email := UPPER(:NEW.email);
  IF UPDATING('SALARY') AND :NEW.salary < :OLD.salary * 0.5 THEN
    RAISE_APPLICATION_ERROR(-20030, '給与を半分未満に下げることはできません');
  END IF;
END;
/

-- 5-2. AFTER 行トリガー：監査ログ（条件付き WHEN 句）
CREATE OR REPLACE TRIGGER emp_salary_audit_trg
  AFTER UPDATE OF salary OR DELETE ON employees
  FOR EACH ROW
  WHEN (NEW.salary IS NULL OR OLD.salary <> NEW.salary)   -- WHEN 句ではコロン不要
BEGIN
  INSERT INTO emp_audit (employee_id, action, old_salary, new_salary)
  VALUES (:OLD.employee_id,
          CASE WHEN DELETING THEN 'DELETE' ELSE 'UPDATE' END,
          :OLD.salary, :NEW.salary);
END;
/

-- 5-3. 複合トリガー（11g+）：行ごとに収集して文の最後にまとめて処理
--      行トリガー内で同じ表を参照すると ORA-04091（変更表エラー）になる問題の定番回避策
CREATE OR REPLACE TRIGGER emp_dept_cap_trg
  FOR UPDATE OF salary ON employees
  COMPOUND TRIGGER
    TYPE t_ids IS TABLE OF employees.department_id%TYPE INDEX BY PLS_INTEGER;
    g_depts t_ids;

  AFTER EACH ROW IS
  BEGIN
    IF :NEW.department_id IS NOT NULL THEN
      g_depts(:NEW.department_id) := :NEW.department_id;
    END IF;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
    v_total NUMBER;
    d       PLS_INTEGER := g_depts.FIRST;
  BEGIN
    WHILE d IS NOT NULL LOOP
      SELECT SUM(salary) INTO v_total FROM employees WHERE department_id = d;
      IF v_total > 200000 THEN
        RAISE_APPLICATION_ERROR(-20040, '部門 ' || d || ' の人件費上限超過');
      END IF;
      d := g_depts.NEXT(d);
    END LOOP;
  END AFTER STATEMENT;
END emp_dept_cap_trg;
/

-- 5-4. INSTEAD OF トリガー：結合ビューを更新可能にする
CREATE OR REPLACE VIEW emp_dept_upd_v AS
  SELECT e.employee_id, e.last_name, d.department_name
  FROM   employees e JOIN departments d ON d.department_id = e.department_id;

CREATE OR REPLACE TRIGGER emp_dept_upd_v_trg
  INSTEAD OF UPDATE ON emp_dept_upd_v
  FOR EACH ROW
BEGIN
  UPDATE employees
  SET    last_name     = :NEW.last_name,
         department_id = (SELECT department_id FROM departments
                          WHERE  department_name = :NEW.department_name)
  WHERE  employee_id   = :OLD.employee_id;
END;
/

