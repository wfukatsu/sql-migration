#!/bin/sh
# Oracle 側にこの検証専用のユーザ `plsqldoc` を作る（samples/oracle-samples/plsql/oracle-user.sh と同じ形）。SYSTEM で 1 度だけ。何度流してもよい。
# plsqldoc_b は build_projects.py が前提の状態を作って読むため、plsqldoc_r はハーネス（plsql_run.py）用。
# 例は HR スキーマ（employees / departments …）を読むので、表は oracle_run.py が例ごとに作り直す。
set -e
cd "$(dirname "$0")/../../difftest"
docker compose exec -T source-oracle sqlplus -s system/oracle@//localhost:1521/FREEPDB1 <<'SQL'
WHENEVER SQLERROR CONTINUE
CREATE USER plsqldoc IDENTIFIED BY plsqldoc QUOTA UNLIMITED ON users;
WHENEVER SQLERROR EXIT FAILURE
GRANT CREATE SESSION, CREATE TABLE, CREATE PROCEDURE, CREATE SEQUENCE, CREATE TRIGGER, CREATE TYPE, CREATE VIEW,
      CREATE SYNONYM, CREATE JOB, CREATE LIBRARY, CREATE MATERIALIZED VIEW, ALTER SESSION TO plsqldoc;
WHENEVER SQLERROR CONTINUE
CREATE USER plsqldoc_b IDENTIFIED BY plsqldoc_b QUOTA UNLIMITED ON users;
WHENEVER SQLERROR EXIT FAILURE
GRANT CREATE SESSION, CREATE TABLE, CREATE PROCEDURE, CREATE SEQUENCE, CREATE TRIGGER, CREATE TYPE, CREATE VIEW,
      CREATE SYNONYM, CREATE JOB, CREATE LIBRARY, CREATE MATERIALIZED VIEW, ALTER SESSION TO plsqldoc_b;
WHENEVER SQLERROR CONTINUE
CREATE USER plsqldoc_r IDENTIFIED BY plsqldoc_r QUOTA UNLIMITED ON users;
WHENEVER SQLERROR EXIT FAILURE
GRANT CREATE SESSION, CREATE TABLE, CREATE PROCEDURE, CREATE SEQUENCE, CREATE TRIGGER, CREATE TYPE, CREATE VIEW,
      CREATE SYNONYM, CREATE JOB, CREATE LIBRARY, CREATE MATERIALIZED VIEW, ALTER SESSION TO plsqldoc_r;
SELECT 'users plsqldoc, plsqldoc_b, plsqldoc_r ready' AS status FROM dual;
SQL
